import type {
  DietaryTag,
  Difficulty,
  Ingredient,
  Recipe,
  RecipeCategory,
  Unit,
} from '@/types';
import { findVocabularyEntry } from './vocabulary';

function ing(name: string, quantity: number, unit: Unit, note?: string): Ingredient {
  const entry = findVocabularyEntry(name);
  if (!entry) {
    throw new Error(`Unknown ingredient "${name}" — add it to src/data/vocabulary.ts first.`);
  }
  return {
    name,
    quantity,
    unit,
    groceryCategory: entry.groceryCategory,
    ...(note ? { note } : {}),
  };
}

interface SeedRecipeInput {
  id: string;
  title: string;
  description: string;
  category: RecipeCategory;
  tags: DietaryTag[];
  prepMinutes: number;
  cookMinutes: number;
  servings: number;
  difficulty: Difficulty;
  emoji: string;
  ingredients: Ingredient[];
  instructions: string[];
  createdAt: string;
}

function recipe(input: SeedRecipeInput): Recipe {
  return {
    id: input.id,
    title: input.title,
    description: input.description,
    category: input.category,
    tags: input.tags,
    prepMinutes: input.prepMinutes,
    cookMinutes: input.cookMinutes,
    servings: input.servings,
    difficulty: input.difficulty,
    image: { emoji: input.emoji },
    ingredients: input.ingredients,
    instructions: input.instructions,
    isCustom: false,
    createdAt: input.createdAt,
    updatedAt: input.createdAt,
  };
}

